/**
 * @file Keyboard class
 * @description Tracks keyboard input states
 */

/**
 * Keyboard input tracker class
 * @class
 */
class Keyboard {
    /**
     * Left arrow or 'A' key state
     * @type {boolean}
     */
    LEFT = false;
    
    /**
     * Right arrow or 'D' key state
     * @type {boolean}
     */
    RIGHT = false;
    
    /**
     * Up arrow key state
     * @type {boolean}
     */
    UP = false;
    
    /**
     * Down arrow key state
     * @type {boolean}
     */
    DOWN = false;
    
    /**
     * Space bar state
     * @type {boolean}
     */
    SPACE = false;
    
    /**
     * 'F' key state (for throwing)
     * @type {boolean}
     */
    f = false;
};

